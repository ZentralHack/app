from fastapi import APIRouter

from app.agent.chat import answer, find_target, suggestions
from app.agent.errors import InvalidInputError
from app.api.deps import KnowledgeBaseDep, LLMDep, RunsDep, SettingsDep
from app.chat_log import log_question
from app.models.contract import ChatRequest, ChatResponse, ChatSuggestions, InstrumentRef

router = APIRouter(prefix="/runs/{run_id}/chat/{program_id}/{instrument_id}")


@router.get("/suggestions")
def chat_suggestions(
    run_id: str, program_id: str, instrument_id: str, kb: KnowledgeBaseDep, runs: RunsDep
) -> ChatSuggestions:
    """Up to three suggested questions, generated by code from the result."""
    ref = InstrumentRef(program_id=program_id, instrument_id=instrument_id)
    return suggestions(find_target(runs.get(run_id).result, ref, kb))


@router.post("")
async def chat(
    run_id: str,
    program_id: str,
    instrument_id: str,
    req: ChatRequest,
    kb: KnowledgeBaseDep,
    llm: LLMDep,
    runs: RunsDep,
    settings: SettingsDep,
) -> ChatResponse:
    """Answers the last message (role `user`) from the result and the program file only."""
    if req.messages[-1].role != "user":
        raise InvalidInputError("Die letzte Nachricht muss eine Frage sein.")
    ref = InstrumentRef(program_id=program_id, instrument_id=instrument_id)
    target = find_target(runs.get(run_id).result, ref, kb)
    response = await answer(target, req.messages, llm)
    log_question(
        settings.chat_log, program_id, instrument_id, req.messages[-1].text, response.basis
    )
    return response
