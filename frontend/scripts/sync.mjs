/*
 * Generates src/api/contract.ts (TypeScript types) from design/contract.schema.json, one named type per $defs entry.
 * Run after the contract changes: npm run sync
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.resolve(root, "../design/contract.schema.json");

const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const ts = await compile(
  { ...schema, title: "Contract", type: "object", properties: {}, additionalProperties: false },
  "Contract",
  {
    unreachableDefinitions: true,
    additionalProperties: false,
    bannerComment: "/* Generated by scripts/sync.mjs from design/contract.schema.json. Do not edit by hand. */",
    style: { singleQuote: false, semi: true },
  },
);
fs.writeFileSync(path.join(root, "src/api/contract.ts"), ts.replace(/^export interface Contract \{\}\n?/m, ""));
console.log("wrote src/api/contract.ts");
